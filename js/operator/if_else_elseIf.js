// kita akan belajar percabangan if else dan else if

// kita akan bedah satu satu dari if, else dan else if

// if
let x = 10;

if (x > 5) {
    console.log("x lebih besar dari 5");
}

// else
let y = 3;  

if (y > 5) {
    console.log("y lebih besar dari 5");
} else {
    console.log("y lebih kecil dari 5");
}

// else if
let nilaiUjian = 80;

if (nilaiUjian >= 90) {
    console.log("nilai A");
} else if (nilaiUjian >= 80) {
    console.log("nilai B");
} else {
    console.log("nilai C");
}