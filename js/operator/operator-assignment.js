// catatan
// += | x += y | x = x + y
// -= | x -= y | x = x - y
// *= | x *= y | x = x * y
// /= | x /= y | x = x / y
// %= | x %= y | x = x % y
// **= | x **= y | x = x ** y

let p = 10;
let q = 2;

console.log(p += q);
console.log(p -= q);
console.log(p *= q);
console.log(p /= q);
console.log(p %= q);
console.log(p **= q);