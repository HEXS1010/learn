// variabel 2 kita akan belajar aritmatika dasar dalam javascript

/* 
    + tambah
    - kurang 
    * kali 
    / bagi
    ** pangkat
    % sisa bagi
*/

const a = 10;
const b = 5;

console.log(a + b); // 15
console.log(a - b); // 5
console.log(a * b); // 50
console.log(a / b); // 2
console.log(a ** b); // 100000
console.log(a % b); // 0

